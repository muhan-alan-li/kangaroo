#!/usr/bin/env python3
"""Extract the resume PDFs to text, so short answers can be grounded in real work.

The resume -- not the profile -- says what the candidate actually built. Read
`candidate/resume-text.md` before writing any free-text answer, and name the bullet you used.

Run this after the resume changes:

    python3 bin/resume_text.py

Writes `candidate/resume-text.md`. Uses `pdftotext -layout` from poppler-utils.
"""

from __future__ import annotations

import datetime
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RESUME_DIR = ROOT / "candidate" / "resume"
DOCS_DIR = ROOT / "candidate" / "documents"
OUT = ROOT / "candidate" / "resume-text.md"


def main() -> int:
    if not shutil.which("pdftotext"):
        print("[resume_text] pdftotext is missing. Install poppler-utils.", file=sys.stderr)
        return 1
    pdfs = sorted(RESUME_DIR.glob("*.pdf"))
    if not pdfs:
        print(f"[resume_text] no PDF found in {RESUME_DIR}", file=sys.stderr)
        return 1

    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    parts = [
        "# Resume text (generated)",
        "",
        f"Generated {stamp} by `bin/resume_text.py`. Do not edit this file by hand:",
        "edit the PDF in `candidate/resume/`, then run `python3 bin/resume_text.py` again.",
        "",
        "**Use this for every free-text answer.** It is the only record of what the candidate",
        "actually built, with the numbers they shipped. The `answers_bank` in",
        "`candidate/candidate_profile.yaml` covers canned screening questions; this file covers",
        "\"tell us about something you built\". Quote the real work, and name the bullet you used.",
        "The supporting documents at the end answer coursework and grade questions.",
        "",
    ]

    def extract(pdf: pathlib.Path) -> str | None:
        try:
            return subprocess.run(
                ["pdftotext", "-layout", str(pdf), "-"],
                check=True, capture_output=True, text=True, timeout=60,
            ).stdout.strip()
        except subprocess.SubprocessError as exc:  # pragma: no cover - surfaced to the operator
            print(f"[resume_text] {pdf.name}: {exc}", file=sys.stderr)
            return None

    for pdf in pdfs:
        text = extract(pdf)
        if text is None:
            return 1
        parts += [f"## {pdf.name}", "", "```text", text, "```", ""]
        print(f"[resume_text] extracted {pdf.name} ({len(text)} chars)")

    if DOCS_DIR.is_dir():
        docs = sorted(DOCS_DIR.glob("*.pdf"))
        if docs:
            parts += ["# Supporting documents (generated)", "",
                      "Transcripts and similar. An education question (\"top 1-2 courses taken and why\")",
                      "is answered from here, with the real course code, title and grade.", ""]
            for pdf in docs:
                text = extract(pdf)
                if text is None:
                    return 1
                parts += [f"## {pdf.name}", "", "```text", text, "```", ""]
                print(f"[resume_text] extracted {pdf.name} ({len(text)} chars)")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"[resume_text] wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

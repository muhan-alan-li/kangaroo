"""Extract the resume PDFs to text, so short answers can be grounded in real work.

The resume -- not the profile -- says what the candidate actually built. Read
`data/candidate/resume-text.md` before writing any free-text answer, and name the bullet you used.

Run this after the resume changes:

    python3 -m server resume-text

Writes `data/candidate/resume-text.md`. Uses `pdftotext -layout` from poppler-utils.
"""

from __future__ import annotations

import argparse
import datetime
import os
import shutil
import subprocess
import sys

from ..config import ROOT
RESUME_DIR = os.path.join(ROOT, "data", "candidate", "resume")
DOCS_DIR = os.path.join(ROOT, "data", "candidate", "documents")
OUT = os.path.join(ROOT, "data", "candidate", "resume-text.md")


def main(argv=None):
    argparse.ArgumentParser(description="Extract the resume PDFs to text.").parse_args(argv)
    if not shutil.which("pdftotext"):
        print("[resume_text] pdftotext is missing. Install poppler-utils.", file=sys.stderr)
        return 1
    pdfs = sorted(p for p in os.listdir(RESUME_DIR) if p.endswith(".pdf"))
    if not pdfs:
        print(f"[resume_text] no PDF found in {RESUME_DIR}", file=sys.stderr)
        return 1

    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    parts = [
        "# Resume text (generated)",
        "",
        f"Generated {stamp} by `python3 -m server resume-text`. Do not edit this file by hand:",
        "edit the PDF in `data/candidate/resume/`, then run `python3 -m server resume-text` again.",
        "",
        "**Use this for every free-text answer.** It is the only record of what the candidate",
        "actually built, with the numbers they shipped. The `answers_bank` in",
        "`data/candidate/candidate_profile.yaml` covers canned screening questions; this file covers",
        "\"tell us about something you built\". Quote the real work, and name the bullet you used.",
        "The supporting documents at the end answer coursework and grade questions.",
        "",
    ]

    def extract(path, name):
        try:
            return subprocess.run(
                ["pdftotext", "-layout", path, "-"],
                check=True, capture_output=True, text=True, timeout=60,
            ).stdout.strip()
        except subprocess.SubprocessError as exc:  # pragma: no cover - surfaced to the operator
            print(f"[resume_text] {name}: {exc}", file=sys.stderr)
            return None

    for pdf in pdfs:
        text = extract(os.path.join(RESUME_DIR, pdf), pdf)
        if text is None:
            return 1
        parts += [f"## {pdf}", "", "```text", text, "```", ""]
        print(f"[resume_text] extracted {pdf} ({len(text)} chars)")

    if os.path.isdir(DOCS_DIR):
        docs = sorted(p for p in os.listdir(DOCS_DIR) if p.endswith(".pdf"))
        if docs:
            parts += ["# Supporting documents (generated)", "",
                      "Transcripts and similar. An education question (\"top 1-2 courses taken and why\")",
                      "is answered from here, with the real course code, title and grade.", ""]
            for pdf in docs:
                text = extract(os.path.join(DOCS_DIR, pdf), pdf)
                if text is None:
                    return 1
                parts += [f"## {pdf}", "", "```text", text, "```", ""]
                print(f"[resume_text] extracted {pdf} ({len(text)} chars)")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(parts) + "\n")
    print(f"[resume_text] wrote {os.path.relpath(OUT, ROOT)}")
    return 0

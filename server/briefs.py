"""The brief cache, and the one thing this server starts.

A brief is generated by `bin/posting_brief.py`: by default one direct DeepSeek call plus a
critic pass (about fifteen seconds), or the older Hermes agent path when contacts need web
research. The POST that requests one launches it detached and answers at once; the client polls
GET /api/posting/<id> until `running` goes false.
"""
from __future__ import annotations

import json
import os
import re
import subprocess

from .config import BRIEFS, BRIEF_SCRIPT, BRIEF_STALE_AFTER, PYTHON, ROOT
from .store import find_row, read_json

# The reword entries the brief generator writes. New briefs use the object shape directly;
# briefs cached before that schema existed hold one free-text sentence, so they are parsed
# into the same fields here rather than left for each client to guess at.
_QUOTES = "[\"\u201c\u2018\u2019']"
_CHANGE_RE = re.compile(
    r'^(?P<where>.*?)\bchange\s+(?P<oq>' + _QUOTES + r')(?P<before>.+)(?P=oq)(?=\s|$)'
    r'\s+to\s+(?P<nq>' + _QUOTES + r')(?P<after>.+)(?P=nq)(?=\s|$)(?P<note>.*)$',
    re.IGNORECASE | re.DOTALL)


def _clean_where(text):
    return re.sub(r'[\.\s]+$', '', (text or '').strip()).strip()


def _clean_note(text):
    return re.sub(r'^\s*[\.\-\u2013\u2014:]\s*', '', (text or '').strip()).strip()


def _clean_advice(text):
    return re.sub(r'\s*[\-\u2013\u2014:]\s*$', '', (text or '').strip()).strip()


# `WHERE: advice "new wording". note` -- the shape old briefs used when the writer
# described the change instead of quoting the line. Matched after the arrow and Change
# forms so a real before/after pair always wins.
_QUOTED_TAIL_RE = re.compile(
    r'^(?P<prefix>.*?)(?P<q>' + _QUOTES + r')(?P<after>.+?)(?P=q)\s*[.]?\s*(?P<note>.*)$',
    re.DOTALL)


def _reword_from_advice(text):
    m = _QUOTED_TAIL_RE.match(text)
    if not m:
        return None
    prefix = m.group('prefix').strip()
    where, advice = '', _clean_advice(prefix)
    # "Apera AI bullet: name both sides" is a location plus an instruction; "Skills, make
    # the cloud coverage explicit" is one instruction that happens to end in a colon. The
    # head before the first colon is a location only when it is short enough to be one.
    if ':' in prefix:
        head, rest = prefix.split(':', 1)
        head = _clean_where(head)
        if head and len(head) <= 60 and len(head.split()) <= 8:
            where, advice = head, _clean_advice(rest)
    return {'where': where, 'before': '', 'after': m.group('after').strip(),
            'advice': advice, 'note': _clean_note(m.group('note'))}


def _reword_fallback(text):
    """Nothing quotable: split at the first colon if there is one, and keep the rest as
    advice so the row still has a left-hand side."""
    if ':' in text:
        where, rest = text.split(':', 1)
        return {'where': _clean_where(where), 'before': '', 'after': '',
                'advice': rest.strip(), 'note': ''}
    return {'where': '', 'before': '', 'after': '', 'advice': text, 'note': ''}


def _reword_from_arrow(text):
    """Split `WHERE: 'old' -> 'new'. note` on the arrow, then unwrap each side's quotes.

    Doing it this way rather than one regex matters because the old and new wording often
    contain apostrophes ("ANSE's"), which a single quote-to-quote pattern cannot tell from
    the closing quote.
    """
    parts = re.split(r'\s*(?:->|\u2192)\s*', text, maxsplit=1)
    if len(parts) != 2:
        return None
    left, right = parts
    m = re.match(r'^(?P<where>.*?)(?P<q>' + _QUOTES + r')(?P<before>.*)(?P=q)\s*$',
                 left, re.DOTALL)
    if m:
        where, before = _clean_where(m.group('where')), m.group('before').strip()
    else:
        where, before = '', left.strip()
    m = re.match(r'^(?P<q>' + _QUOTES + r')(?P<after>.*)(?P=q)(?=\s|$)(?P<note>.*)$',
                 right, re.DOTALL)
    if m:
        after, note = m.group('after').strip(), _clean_note(m.group('note'))
    else:
        after, note = right.strip(), ''
    return {'where': where, 'before': before, 'after': after, 'advice': '', 'note': note}


def normalize_reword(item):
    """One reword entry as `{where, before, after, advice, note}`, from either the new
    object schema or an old free-text string.

    `before`/`after` are an explicit replacement pair. When a legacy string named the
    change instead of quoting the old line, there is no `before`: the instruction goes in
    `advice` and the quoted new wording in `after`, so the two-column view still has a
    left-hand side to show.
    """
    if isinstance(item, dict):
        return {
            'where': str(item.get('where') or '').strip(),
            'before': str(item.get('before') or '').strip(),
            'after': str(item.get('after') or item.get('to') or item.get('new') or '').strip(),
            'advice': str(item.get('advice') or '').strip(),
            'note': str(item.get('note') or '').strip(),
        }
    text = str(item or '').strip()
    # Explicit before/after first (arrow, then Change ... to ...), so an instruction that
    # happens to contain the word "change" is not mistaken for the advice form.
    parsed = _reword_from_arrow(text) or _reword_from_change(text) or _reword_from_advice(text)
    return parsed or _reword_fallback(text)


def _reword_from_change(text):
    match = _CHANGE_RE.match(text)
    if not match:
        return None
    return {'where': _clean_where(match.group('where')),
            'before': match.group('before').strip(),
            'after': match.group('after').strip(),
            'advice': '',
            'note': _clean_note(match.group('note'))}


def normalize_brief(data):
    """Give `tailoring.reword` one shape for every brief, however it was written."""
    if not isinstance(data, dict):
        return data
    tailoring = data.get('tailoring')
    if not isinstance(tailoring, dict):
        return data
    rewords = tailoring.get('reword')
    if isinstance(rewords, list):
        tailoring['reword'] = [normalize_reword(x) for x in rewords]
    return data


def brief_for(pid):
    """The brief for a posting: its state, the result, and whether a run is in flight.

    A `.running` marker that has gone stale (a run that died without writing a result) is
    reported as stale rather than running, so the button can be pressed again instead of the
    panel spinning forever.
    """
    data = normalize_brief(read_json(os.path.join(BRIEFS, f"{pid}.json")))
    marker = read_json(os.path.join(BRIEFS, f"{pid}.running"))
    running, started = False, None
    if marker:
        started = marker.get("started_at")
        age = None
        try:
            from datetime import datetime, timezone
            stamp = datetime.fromisoformat(str(started).replace("Z", "+00:00"))
            age = (datetime.now(timezone.utc) - stamp).total_seconds()
        except Exception:  # noqa: BLE001
            age = None
        running = age is None or age < BRIEF_STALE_AFTER
    return {"brief": data, "running": running, "started_at": started,
            "stale": bool(marker) and not running,
            "has_script": os.path.exists(BRIEF_SCRIPT)}


def start_brief(pid):
    """Spawn the generator for one posting. Returns (ok, message).

    Detached on purpose: the request must answer immediately. The default direct engine returns
    in seconds; the agent engine takes a couple of minutes because it reads pages.
    `posting_brief.py` writes both the running marker and the result, so this only has to launch
    it and refuse to launch a second one.
    """
    state = brief_for(pid)
    if state["running"]:
        return True, "already running"
    if not os.path.exists(BRIEF_SCRIPT):
        return False, f"no generator at {BRIEF_SCRIPT}"
    if not find_row(pid):
        return False, f"no posting {pid} in the portal feed"
    os.makedirs(BRIEFS, exist_ok=True)
    # The marker is written here as well as in the child, so two clicks in the same second
    # cannot both pass the check above and start two agent runs.
    with open(os.path.join(BRIEFS, f"{pid}.running"), "w", encoding="utf-8") as fh:
        json.dump({"started_at": _now_iso(), "launcher": "dashboard", "pid": None}, fh)
    try:
        subprocess.Popen([PYTHON, BRIEF_SCRIPT, str(pid)],
                         cwd=ROOT, stdin=subprocess.DEVNULL,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                         start_new_session=True)
    except Exception as exc:  # noqa: BLE001
        return False, f"could not start the generator: {exc}"
    return True, "started"


def start_contacts(pid):
    """Start the second-level (Hermes agent) contact search for one posting.

    Same contract as `start_brief`: the POST answers at once, the child writes the same
    `running` marker, and the page polls GET /api/posting/<id> until it clears. The child runs
    `posting_brief.py --deep-contacts`, which merges contacts into the existing brief.
    """
    state = brief_for(pid)
    if state["running"]:
        return True, "already running"
    if not os.path.exists(BRIEF_SCRIPT):
        return False, f"no generator at {BRIEF_SCRIPT}"
    if not find_row(pid):
        return False, f"no posting {pid} in the portal feed"
    os.makedirs(BRIEFS, exist_ok=True)
    with open(os.path.join(BRIEFS, f"{pid}.running"), "w", encoding="utf-8") as fh:
        json.dump({"started_at": _now_iso(), "launcher": "dashboard", "pid": None,
                   "mode": "deep-contacts"}, fh)
    try:
        subprocess.Popen([PYTHON, BRIEF_SCRIPT, str(pid), "--deep-contacts"],
                         cwd=ROOT, stdin=subprocess.DEVNULL,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                         start_new_session=True)
    except Exception as exc:  # noqa: BLE001
        return False, f"could not start the contact search: {exc}"
    return True, "started"


def _now_iso():
    from datetime import datetime, timezone
    return datetime.now(timezone.utc).isoformat(timespec="seconds")
